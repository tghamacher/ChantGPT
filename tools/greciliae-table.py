# Writes js/greciliae.js, the table of a Gregorio font's glyphs: name -> [character, width]. Run by
# tools/build-greciliae.sh, under FontForge: fontforge -lang=py -script greciliae-table.py <font.ttf> <out.js>
import fontforge, json, os, sys
f = fontforge.open(sys.argv[1])
glyphs = {g.glyphname: [g.unicode, g.width] for g in f.glyphs() if g.unicode >= 0}
version = os.environ.get('VERSION', f.version)
out = ("// Generated by tools/build-greciliae.sh from fonts/greciliae.ttf (Gregorio " + version + "): each glyph's name, its\n"
       "// character (in the font's private use area) and its width, in font units (1000 to the em). Don't edit by hand.\n"
       "(function (global) {\n  'use strict';\n  const G = " + json.dumps(dict(sorted(glyphs.items())), separators=(',', ':')) + ";\n"
       "  global.CGGreciliae = { version: '" + version + "', em: 1000, step: 157.5, glyphs: G };\n"
       "  if (typeof module === 'object' && module.exports) module.exports = global.CGGreciliae;\n"
       "})(typeof window !== 'undefined' ? window : globalThis);\n")
open(sys.argv[2], 'w').write(out)
print(len(glyphs), 'glyphs')
